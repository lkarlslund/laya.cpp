#!/usr/bin/env python3
"""Record GPU rotary rounding corrections for every supported position (development only)."""
import argparse
from pathlib import Path
import numpy as np
import torch


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path)
    p.add_argument('--check',action='store_true')
    a=p.parse_args()
    runtime='rocm' if torch.version.hip else 'cuda'
    if not torch.__version__.startswith('2.11.0') or (runtime=='cuda' and torch.version.cuda!='13.0') or (runtime=='rocm' and not torch.version.hip.startswith('7.13.')):
        p.error('Requires PyTorch 2.11 and CUDA 13.0 or ROCm 7.13')
    if a.output is None:a.output=Path(f'src/vulkan/rotary_{runtime}.hpp')
    inv_bits=[];deltas=[];values=[]
    for base in [160000,10000]:
        inv=1.0/(base**(torch.arange(0,64,2).float()/64))
        inv_bits.extend(inv.numpy().view(np.uint32).tolist())
        angles=torch.arange(1024,device='cuda',dtype=torch.float32)[:,None]*inv.cuda()[None,:]
        for name in ['cos','sin']:
            gpu=getattr(torch,name)(angles).cpu().numpy()
            host=getattr(np,name)(angles.cpu().numpy().astype(np.float64)).astype(np.float32)
            delta=gpu.view(np.uint32).astype(np.int64)-host.view(np.uint32).astype(np.int64)
            if not ((delta>=-1)&(delta<=1)).all():raise RuntimeError('Rotary correction exceeds one ULP')
            deltas.extend((delta.flatten()+1).tolist());values.extend(gpu.view(np.uint32).flatten().tolist())
    packed=[sum(deltas[i+j]<<(2*j) for j in range(4)) for i in range(0,len(deltas),4)]
    fingerprint=14695981039346656037
    for v in values:
        for shift in [0,8,16,24]:fingerprint=((fingerprint^((v>>shift)&255))*1099511628211)&((1<<64)-1)
    lines=['#pragma once','#include <cstdint>','namespace laya::vulkan_precision {',
           '// Generated by benchmarks/generate_rotary_tables.py.',
           '// Two-bit corrections relative to host double sin/cos rounded to float.',
           f'inline constexpr uint32_t rotary_{runtime}_inverse[64]={{']
    lines += [','.join(hex(v) for v in inv_bits[i:i+8])+',' for i in range(0,64,8)]
    lines += ['};',f'inline constexpr uint8_t rotary_{runtime}_corrections[32768]={{']
    lines += [','.join(hex(v) for v in packed[i:i+32])+',' for i in range(0,len(packed),32)]
    lines += ['};',f'inline constexpr uint64_t rotary_{runtime}_fingerprint={fingerprint}ull;','}']
    text='\n'.join(lines)+'\n'
    if a.check:
        if a.output.read_text()!=text:raise SystemExit('Rotary numerical table differs')
        print('All 131,072 rotary values match')
    else:a.output.write_text(text)

if __name__=='__main__':main()
