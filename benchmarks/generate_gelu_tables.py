#!/usr/bin/env python3
"""Generate exhaustive mixed-precision GELU numerical tables (development only)."""
import argparse
import re
import math
from pathlib import Path
import torch


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=None)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    rocm=bool(torch.version.hip)
    if args.output is None: args.output=Path('src/vulkan/gelu_rocm_patches.hpp' if rocm else 'src/vulkan/gelu_tables.hpp')
    if rocm:
        if not torch.__version__.startswith('2.11.0') or not torch.version.hip.startswith('7.13.'):
            parser.error('ROCm tables require PyTorch 2.11 / ROCm 7.13')
    elif torch.version.cuda!='13.0' or not torch.__version__.startswith('2.11.0'):
        parser.error('This table records the PyTorch 2.11 CUDA 13.0 numerical contract')
    out=['#pragma once','#include <cstdint>','namespace laya::vulkan_precision {',
         '// Generated by benchmarks/generate_gelu_tables.py; no runtime Python dependency.',
         '// Exhaustive GELU outputs: PyTorch 2.11 CUDA 13.0, round-to-nearest.']
    if rocm:
        base=Path('src/vulkan/gelu_tables.hpp').read_text()
        out=['#pragma once','#include <cstdint>','namespace laya::vulkan_precision {',
             '// Generated numerical differences: PyTorch 2.11 ROCm 7.13 versus the CUDA table.',
             'struct gelu_patch { uint16_t index, value; };']
    for name,dtype in [('fp16',torch.float16),('bf16',torch.bfloat16)]:
        inputs=torch.arange(65536,dtype=torch.int32,device='cuda').to(torch.int16).view(dtype)
        values=torch.nn.functional.gelu(inputs).float().cpu().to(dtype).view(torch.int16).tolist()
        if rocm:
            payload=re.search(r'gelu_'+name+r'_nvidia\[65536\]=\{(.*?)\};',base,re.S).group(1)
            original=[int(x,16) for x in re.findall(r'0x[0-9a-f]+',payload)]
            base_values=torch.tensor(original,dtype=torch.int32).to(torch.int16).view(dtype).float().tolist()
            new_values=torch.tensor(values,dtype=torch.int16).view(dtype).float().tolist()
            # Signed zeros are part of the low-precision input contract too:
            # matrix instructions can produce different rounded sums for them.
            changes=[(i,v) for i,(a,b,v,old) in enumerate(zip(base_values,new_values,values,original))
                     if (v & 65535)!=old and not (math.isnan(a) and math.isnan(b))]
            out.append(f'inline constexpr gelu_patch gelu_{name}_rocm[]={{')
            out += [f'{{{i},{hex(v & 65535)}}},' for i,v in changes]
            out.append('};')
            continue
        out.append(f'inline constexpr uint16_t gelu_{name}_nvidia[65536]={{')
        out += [','.join(hex(v & 65535) for v in values[i:i+32])+',' for i in range(0,65536,32)]
        out.append('};')
    out.append('}')
    text='\n'.join(out)+'\n'
    if args.check:
        if args.output.read_text()!=text: raise SystemExit('GELU numerical table differs')
        print('All 131,072 GELU values match (NaN payloads ignored)' if rocm else 'All 131,072 GELU values match')
    else: args.output.write_text(text)

if __name__=='__main__': main()
